import { createHash } from "node:crypto";

import type { BrainConfig } from "./config.js";

export const SCHEMA_VERSION = 1;

export interface ContextFile {
  path: string;
  content: string;
}

export interface DocumentModel {
  project: BrainConfig["project"];
  conventions: string[];
  contextFiles: ContextFile[];
  scripts: Record<string, string>;
}

export interface Target {
  name: string;
  outputPath: string;
  render(model: DocumentModel): string;
}

function line(value: string): string {
  return value.endsWith("\n") ? value : `${value}\n`;
}

export function documentFromConfig(config: BrainConfig, contextFiles: ContextFile[] = []): DocumentModel {
  return {
    project: config.project,
    conventions: [...config.conventions],
    contextFiles: [...contextFiles],
    scripts: Object.fromEntries(Object.entries(config.scripts).sort(([a], [b]) => a.localeCompare(b))),
  };
}

export function renderMarkdownBody(model: DocumentModel): string {
  const sections: string[] = [
    `# ${model.project.name}`,
    model.project.summary,
    "## Conventions",
    model.conventions.length === 0 ? "No conventions configured." : model.conventions.map((rule) => `- ${rule}`).join("\n"),
  ];

  if (model.contextFiles.length > 0) {
    sections.push("## Project context");
    for (const file of model.contextFiles) {
      sections.push(`### \`${file.path}\`\n\n${file.content.trimEnd()}`);
    }
  }

  const scripts = Object.entries(model.scripts);
  if (scripts.length > 0) {
    sections.push(
      "## Declared scripts\n" + scripts.map(([name, command]) => `- \`${name}\`: \`${command}\``).join("\n"),
    );
  }

  return line(`${sections.join("\n\n")}\n`);
}

export function contentHash(body: string): string {
  return createHash("sha256").update(body).digest("hex").slice(0, 16);
}

export function generatedMarker(body: string): string {
  return `<!-- generated by brainstem v${SCHEMA_VERSION} · ${contentHash(body)} · edit brain.toml instead -->`;
}

export function renderMarked(body: string): string {
  return `${generatedMarker(body)}\n\n${body}`;
}

const FRONTMATTER = /^(---\n[\s\S]*?\n---\n)\n?/;

/**
 * Cursor .mdc files and skill manifests require YAML frontmatter to be the very first
 * bytes of the file. A marker above it silently breaks their parsers, so the marker goes
 * immediately after the closing `---` instead.
 */
export function renderMarkedAfterFrontmatter(body: string): string {
  const match = body.match(FRONTMATTER);
  if (!match) return renderMarked(body);
  const frontmatter = match[1];
  const rest = body.slice(frontmatter.length).replace(/^\n+/, "");
  return `${frontmatter}\n${generatedMarker(body)}\n\n${rest}`;
}

export function renderGeneratedMarkdown(model: DocumentModel): string {
  const body = renderMarkdownBody(model);
  return renderMarked(body);
}

export function hasGeneratedMarker(text: string): boolean {
  const marker = `<!-- generated by brainstem v${SCHEMA_VERSION} \u00b7 [0-9a-f]{16} \u00b7 edit brain\\.toml instead -->`;
  return new RegExp(`^(?:---\\n[\\s\\S]*?\\n---\\n\\n)?${marker}`).test(text);
}
