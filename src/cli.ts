#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { ConfigError, EXAMPLE_CONFIG, loadConfig } from "./config.js";
import { loadContextFiles } from "./context.js";
import { documentFromConfig, hasGeneratedMarker } from "./render.js";
import { targetList } from "./targets/index.js";

interface BuildOptions {
  check: boolean;
  force: boolean;
  out: string;
}

function usageError(message: string): never {
  throw new ConfigError(`${message}; run "brainstem --help" for usage`);
}

function parseBuildOptions(args: string[], root: string): BuildOptions {
  const options: BuildOptions = { check: false, force: false, out: root };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--check") {
      options.check = true;
    } else if (arg === "--force") {
      options.force = true;
    } else if (arg === "--out") {
      const value = args[++index];
      if (!value || value.startsWith("--")) usageError("--out needs a directory");
      options.out = resolve(root, value);
    } else {
      usageError(`unknown build option ${arg}`);
    }
  }
  if (options.check && options.force) usageError("--check and --force cannot be combined");
  return options;
}

async function init(root: string): Promise<void> {
  const path = resolve(root, "brain.toml");
  try {
    await readFile(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      await writeFile(path, EXAMPLE_CONFIG, "utf8");
      console.log(`created ${path}`);
      return;
    }
    throw new ConfigError(`could not inspect brain.toml: ${String(error)}`);
  }
  throw new ConfigError(`brain.toml already exists; move it before running "brainstem init"`);
}

async function build(root: string, args: string[]): Promise<number> {
  const config = await loadConfig(root);
  const options = parseBuildOptions(args, root);
  const contextFiles = await loadContextFiles(root, config);
  const model = documentFromConfig(config, contextFiles);
  let stale = false;

  for (const target of targetList) {
    if (!config.targets[target.name as keyof typeof config.targets]) {
      continue;
    }
    const outputPath = resolve(options.out, target.outputPath);
    const expected = target.render(model);
    let actual: string | undefined;
    try {
      actual = await readFile(outputPath, "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
        throw new ConfigError(`could not read ${target.outputPath}: ${String(error)}`);
      }
    }

    if (options.check) {
      if (actual === undefined) {
        console.error(`stale target: ${target.outputPath} is missing`);
        stale = true;
      } else if (!hasGeneratedMarker(actual)) {
        throw new ConfigError(`${target.outputPath} is not generated by brainstem; move it or pass --force`);
      } else if (actual !== expected) {
        console.error(`stale target: ${target.outputPath} differs from brain.toml`);
        stale = true;
      } else {
        console.log(`clean: ${target.outputPath}`);
      }
      continue;
    }

    if (actual !== undefined && !hasGeneratedMarker(actual) && !options.force) {
      throw new ConfigError(`${target.outputPath} is hand-written; move it or pass --force`);
    }
    await mkdir(resolve(outputPath, ".."), { recursive: true });
    if (actual !== expected) await writeFile(outputPath, expected, "utf8");
    console.log(`generated ${target.outputPath}`);
  }
  return stale ? 1 : 0;
}

async function listTargets(root: string): Promise<number> {
  const config = await loadConfig(root);
  for (const target of targetList) {
    console.log(`${target.name}\t${config.targets[target.name as keyof typeof config.targets] ? "enabled" : "disabled"}\t${target.outputPath}`);
  }
  return 0;
}

function help(): void {
  console.log(`brainstem — one brain, every agent

Usage:
  brainstem init
  brainstem build [--check] [--force] [--out <dir>]
`);
}

export async function main(argv = process.argv.slice(2), root = process.cwd()): Promise<number> {
  const [command, ...args] = argv;
  if (!command || command === "--help" || command === "-h") {
    help();
    return 0;
  }
  if (command === "init") {
    if (args.length > 0) usageError("init takes no options");
    await init(root);
    return 0;
  }
  if (command === "build") return build(root, args);
  if (command === "targets") {
    if (args.length > 0) usageError("targets takes no options");
    return listTargets(root);
  }
  usageError(`unknown command ${command}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().then((code) => {
    process.exitCode = code;
  }).catch((error: unknown) => {
    const message = error instanceof Error ? error.message : String(error);
    console.error(message.replace(/\n/g, " "));
    process.exitCode = error instanceof ConfigError ? 2 : 1;
  });
}
