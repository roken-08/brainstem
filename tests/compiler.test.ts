import { strict as assert } from "node:assert";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";

import { main } from "../src/cli.js";
import { parseConfig } from "../src/config.js";
import { documentFromConfig, generatedMarker, renderMarkdownBody } from "../src/render.js";
import { targetList } from "../src/targets/index.js";

const configText = `
[project]
name = "demo"
summary = "A project used for compiler tests."

[conventions]
rules = ["Run tests first."]

[scripts]
test = "node --test"

[targets]
agents = true
claude = true
cursor = true
copilot = true
skill = true
`;

test("all five adapters render their stable native wrappers", () => {
  const model = documentFromConfig(parseConfig(configText));
  const markdownBody = renderMarkdownBody(model);
  const expected = new Map([
    ["agents", `${generatedMarker(markdownBody)}\n\n${markdownBody}`],
    ["claude", `${generatedMarker(markdownBody)}\n\n${markdownBody}`],
    ["copilot", `${generatedMarker(markdownBody)}\n\n${markdownBody}`],
    [
      "cursor",
      `${generatedMarker(`---\ndescription: brainstem instructions\nglobs:\nalwaysApply: true\n---\n\n${markdownBody}`)}\n\n---\ndescription: brainstem instructions\nglobs:\nalwaysApply: true\n---\n\n${markdownBody}`,
    ],
    [
      "skill",
      `${generatedMarker(`---\nname: brainstem\ndescription: Project instructions generated from brain.toml\n---\n\n${markdownBody}`)}\n\n---\nname: brainstem\ndescription: Project instructions generated from brain.toml\n---\n\n${markdownBody}`,
    ],
  ]);

  for (const target of targetList) {
    assert.equal(target.outputPath.length > 0, true);
    assert.equal(target.render(model), expected.get(target.name));
  }
});

test("build checks every enabled target and detects drift", async () => {
  const root = await mkdtemp(join(tmpdir(), "brainstem-compiler-"));
  await writeFile(join(root, "brain.toml"), configText, "utf8");

  assert.equal(await main(["build"], root), 0);
  assert.equal(await main(["build", "--check"], root), 0);

  const agentsPath = join(root, "AGENTS.md");
  await writeFile(agentsPath, `${await readFile(agentsPath, "utf8")}\nmanual drift\n`, "utf8");
  assert.equal(await main(["build", "--check"], root), 1);
});

test("build refuses to clobber an unmarked target", async () => {
  const root = await mkdtemp(join(tmpdir(), "brainstem-clobber-"));
  await writeFile(join(root, "brain.toml"), configText, "utf8");
  await writeFile(join(root, "AGENTS.md"), "hand-written instructions\n", "utf8");

  await assert.rejects(main(["build"], root), /AGENTS\.md is hand-written/);
  assert.equal(await main(["build", "--force"], root), 0);
  assert.match(await readFile(join(root, "AGENTS.md"), "utf8"), /^<!-- generated by brainstem/);
});

test("an initialized project builds before optional context files exist", async () => {
  const root = await mkdtemp(join(tmpdir(), "brainstem-init-"));
  assert.equal(await main(["init"], root), 0);
  assert.equal(await main(["build"], root), 0);
  assert.equal(await main(["build", "--check"], root), 0);
});
